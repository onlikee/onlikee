// @vitest-environment jsdom
/* eslint-disable vue/one-component-per-file -- Independent composition fixtures. */
import { flushPromises, mount, type VueWrapper } from '@vue/test-utils'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { createCommentVNode, createSSRApp, defineComponent, Fragment, h, nextTick, ref } from 'vue'
import { renderToString } from '@vue/server-renderer'
import { LabelGroup } from './index'
import { Label } from '../Label'
import { Link } from '../Link'
import { Token } from '../Token'

const CustomRoot = defineComponent({
  inheritAttrs: false,
  setup(_props, { attrs, slots, expose }) {
    const element = ref<HTMLElement | null>(null)
    expose({ element })
    return () => h('div', { ...attrs, ref: element }, slots.default?.())
  },
})

const wrappers: VueWrapper[] = []
async function settle() {
  await nextTick()
  await flushPromises()
  await nextTick()
}
function labels() {
  return ['One', 'Two', 'Three', 'Four', 'Five'].map((label) =>
    h(Label, { key: label }, { default: () => label }),
  )
}
function fixture(props: Record<string, unknown> = {}, children = labels) {
  const wrapper = mount(LabelGroup, {
    props,
    slots: { default: children },
    attachTo: document.body,
  })
  wrappers.push(wrapper)
  return wrapper
}
beforeEach(() => {
  vi.spyOn(HTMLElement.prototype, 'offsetWidth', 'get').mockReturnValue(100)
  vi.spyOn(HTMLElement.prototype, 'offsetHeight', 'get').mockReturnValue(30)
  vi.spyOn(HTMLElement.prototype, 'offsetParent', 'get').mockReturnValue(document.body)
  vi.spyOn(HTMLElement.prototype, 'getClientRects').mockImplementation(function (
    this: HTMLElement,
  ) {
    return [this.getBoundingClientRect()] as unknown as DOMRectList
  })
})
afterEach(() => {
  wrappers.forEach((wrapper) => wrapper.unmount())
  wrappers.length = 0
  document.body.innerHTML = ''
  vi.restoreAllMocks()
  vi.unstubAllGlobals()
})

describe('LabelGroup', () => {
  it('only forwards class and the documented options, without a public DOM ref', async () => {
    const click = vi.fn()
    const wrapper = fixture({
      id: 'ignored',
      title: 'ignored',
      style: { gap: '20px' },
      class: 'vue-class',
      className: 'source-class',
      onClick: click,
    })
    expect(wrapper.attributes('id')).toBeUndefined()
    expect(wrapper.attributes('title')).toBeUndefined()
    expect(wrapper.attributes('style')).toBeUndefined()
    expect(wrapper.classes()).toEqual(expect.arrayContaining(['vue-class', 'source-class']))
    expect('element' in wrapper.vm).toBe(false)
    await wrapper.trigger('click')
    expect(click).not.toHaveBeenCalled()
  })

  it.each(['inline', 'overlay'])(
    'resolves a custom root DOM ref for %s truncation',
    async (overflowStyle) => {
      const wrapper = fixture({ as: CustomRoot, visibleChildCount: 1, overflowStyle }, () => [
        h(Label, {}, () => 'Public'),
        h(Label, { as: Link, href: '#labels' }, () => 'Labels'),
      ])
      await settle()
      expect(wrapper.element.tagName).toBe('DIV')
      expect(wrapper.findAll(':scope > span[data-index]')).toHaveLength(2)
      await wrapper.get('button').trigger('click')
      await settle()
      if (overflowStyle === 'inline') {
        expect(document.activeElement).toBe(wrapper.get('a').element)
      } else {
        expect(document.querySelector('[role="dialog"] a')?.textContent).toBe('Labels')
      }
    },
  )

  it('observes the DOM element exposed by a custom root', async () => {
    const observe = vi.fn()
    let root: Element | Document | null | undefined
    vi.stubGlobal(
      'IntersectionObserver',
      class {
        constructor(_callback: IntersectionObserverCallback, options: IntersectionObserverInit) {
          root = options.root
        }
        observe = observe
        disconnect = vi.fn()
      },
    )
    const wrapper = fixture({ as: CustomRoot, visibleChildCount: 'auto' })
    await settle()
    expect(root).toBe(wrapper.element)
    expect(observe).toHaveBeenCalledTimes(5)
  })

  it('counts explicit fragments as one child and keeps null child index positions', async () => {
    const wrapper = fixture({ visibleChildCount: 1, overflowStyle: 'inline' }, () => [
      h(Fragment, {}, [h(Label, {}, () => 'One'), h(Label, {}, () => 'Two')]),
      createCommentVNode('conditional child'),
      h(Label, {}, () => 'Three'),
    ])
    await settle()
    expect(wrapper.findAll('[data-index]')).toHaveLength(2)
    expect(wrapper.get('[data-index="0"]').findAll('[data-component="Label"]')).toHaveLength(2)
    expect(wrapper.get('[data-index="2"]').text()).toBe('Three')
    expect(wrapper.get('button').text()).toContain('+1')
  })

  it('flattens compiler list fragments generated by v-for', async () => {
    const List = defineComponent({
      components: { LabelGroup, Badge: Label },
      setup: () => ({ labels: ['One', 'Two', 'Three'] }),
      template:
        '<LabelGroup :visible-child-count="1" overflow-style="inline"><Badge v-for="text in labels" :key="text">{{ text }}</Badge></LabelGroup>',
    })
    const wrapper = mount(List, { attachTo: document.body })
    wrappers.push(wrapper)
    await settle()
    expect(wrapper.findAll('[data-index]')).toHaveLength(3)
    expect(wrapper.get('button').text()).toContain('+2')
  })

  it('supports interactive removable tokens after inline expansion without stealing focus from another group', async () => {
    const click = vi.fn()
    const texts = ref(['One', 'Two', 'Three'])
    const children = () =>
      texts.value.map((text) =>
        h(Token, {
          as: 'button',
          text,
          onClick: click,
          onRemove: () => {
            texts.value = texts.value.filter((value) => value !== text)
          },
        }),
      )
    fixture({ visibleChildCount: 1, overflowStyle: 'inline' }, children)
    const wrapper = fixture({ visibleChildCount: 1, overflowStyle: 'inline' }, children)
    await settle()
    await wrapper.get('[data-component="LabelGroup.Toggle"] button').trigger('click')
    await settle()
    const token = wrapper.get('[data-index="1"] button')
    expect(document.activeElement).toBe(token.element)
    await token.trigger('click')
    expect(click).toHaveBeenCalledOnce()
    await token.trigger('keydown', { key: 'Backspace' })
    await settle()
    expect(texts.value).toEqual(['One', 'Three'])
    expect(wrapper.findAll('[data-index]')).toHaveLength(2)
    await wrapper.get('[data-component="LabelGroup.Toggle"] button').trigger('click')
    await settle()
    await vi.waitFor(() =>
      expect(document.activeElement).toBe(
        wrapper.get('[data-component="LabelGroup.Toggle"] button').element,
      ),
    )
  })

  it('preserves interactive token handlers when rendering all children in the overlay', async () => {
    const click = vi.fn()
    const remove = vi.fn()
    const wrapper = fixture({ visibleChildCount: 1 }, () => [
      h(Token, { as: 'button', text: 'One' }),
      h(Token, { as: 'button', text: 'Two', onClick: click, onRemove: remove }),
    ])
    await settle()
    await wrapper.get('[data-component="LabelGroup.Toggle"] button').trigger('click')
    await settle()
    const token = document.querySelectorAll<HTMLButtonElement>('[role="dialog"] button')[1]!
    token.click()
    token.dispatchEvent(new KeyboardEvent('keydown', { key: 'Delete', bubbles: true }))
    expect(click).toHaveBeenCalledOnce()
    expect(remove).toHaveBeenCalledOnce()
  })

  it('hydrates all children before calculating numeric truncation without mismatches', async () => {
    const options = { render: () => h(LabelGroup, { visibleChildCount: 1 }, { default: labels }) }
    const host = document.createElement('div')
    document.body.append(host)
    host.innerHTML = await renderToString(createSSRApp(options))
    expect(host.querySelector('button')).toBeNull()
    expect(host.querySelectorAll('[data-index]')).toHaveLength(5)
    const original = host.firstElementChild
    const warn = vi.spyOn(console, 'warn')
    const error = vi.spyOn(console, 'error')
    const app = createSSRApp(options)
    try {
      app.mount(host)
      await settle()
      expect(host.firstElementChild).toBe(original)
      expect(host.querySelector('button')?.textContent).toContain('+4')
      host.querySelector<HTMLButtonElement>('button')!.click()
      await settle()
      expect(document.querySelectorAll('[role="dialog"] [data-component="Label"]')).toHaveLength(5)
      expect(warn).not.toHaveBeenCalled()
      expect(error).not.toHaveBeenCalled()
    } finally {
      app.unmount()
      host.remove()
    }
  })

  it.each(['ul', 'ol'])('renders %s items and wraps every label', (as) => {
    const wrapper = fixture({ as, className: 'custom', id: 'labels' })
    expect(wrapper.element.tagName.toLowerCase()).toBe(as)
    expect(wrapper.attributes('data-component')).toBe('LabelGroup')
    expect(wrapper.attributes('data-list')).toBe('true')
    expect(wrapper.findAll(':scope > li')).toHaveLength(5)
    expect(wrapper.attributes('data-overflow')).toBe('inline')
    expect(wrapper.classes()).toContain('custom')
    expect(wrapper.attributes('id')).toBeUndefined()
  })
  it('renders custom roots without list wrappers, including fragment slot children', () => {
    const wrapper = fixture({ as: 'div' })
    expect(wrapper.findAll('li')).toHaveLength(0)
    expect(wrapper.findAll('[data-component="Label"]')).toHaveLength(5)
    expect(wrapper.attributes('data-list')).toBeUndefined()
  })
  it('truncates to a fixed count, updates when props or children change, and treats zero as untruncated', async () => {
    const count = ref(5)
    const wrapper = fixture({ visibleChildCount: 3, overflowStyle: 'inline' }, () =>
      labels().slice(0, count.value),
    )
    await settle()
    expect(wrapper.get('button').text()).toBe('Show +2 more+2')
    expect(
      wrapper
        .get('[data-index="3"]')
        .classes()
        .some((name) => name.includes('hidden')),
    ).toBe(true)
    await wrapper.setProps({ visibleChildCount: 1 })
    expect(wrapper.get('button').text()).toContain('+4')
    count.value = 3
    await nextTick()
    expect(wrapper.findAll('[data-index]')).toHaveLength(3)
    expect(wrapper.get('button').text()).toContain('+2')
    await wrapper.setProps({ visibleChildCount: 0 })
    expect(wrapper.find('button').exists()).toBe(false)
    expect(wrapper.find('[data-component="LabelGroup.Toggle"]').exists()).toBe(false)
  })
  it('expands inline and restores focus to its own toggle without affecting another instance', async () => {
    const first = fixture({ visibleChildCount: 1, overflowStyle: 'inline' })
    const second = fixture({ visibleChildCount: 1, overflowStyle: 'inline' })
    await settle()
    await second.get('button').trigger('click')
    await settle()
    expect(second.attributes('data-overflow')).toBe('inline')
    expect(second.get('button').text()).toBe('Show less')
    await vi.waitFor(() => expect(document.activeElement).toBe(second.get('button').element))
    expect(first.get('button').text()).toContain('+4')
    await second.get('button').trigger('click')
    await settle()
    expect(second.get('button').text()).toContain('+4')
    await vi.waitFor(() => expect(document.activeElement).toBe(second.get('button').element))
  })
  it('focuses the first newly revealed focusable child', async () => {
    const wrapper = fixture({ visibleChildCount: 1, overflowStyle: 'inline' }, () => [
      h(Label, null, { default: () => 'Plain' }),
      h(Label, { as: 'a', href: '#issue', id: 'hidden-link' }, () => 'Issue'),
      h(Label, null, { default: () => 'Last' }),
    ])
    await settle()
    await wrapper.get('button').trigger('click')
    await settle()
    expect(document.activeElement?.id).toBe('hidden-link')
  })
  it('opens all labels in a named modal overlay by keyboard and restores focus on Escape', async () => {
    const wrapper = fixture({ visibleChildCount: 3 })
    await settle()
    const expand = wrapper.get('button')
    await expand.trigger('keydown', { key: 'Enter' })
    await settle()
    const dialog = document.querySelector<HTMLElement>('[role="dialog"]')
    expect(dialog?.getAttribute('aria-label')).toBe('All 5 labels')
    expect(dialog?.getAttribute('aria-modal')).toBe('true')
    expect(dialog?.querySelectorAll('[data-component="Label"]')).toHaveLength(5)
    expect(document.activeElement).toBe(
      dialog?.querySelector('button[data-component="IconButton"]'),
    )
    document.activeElement?.dispatchEvent(
      new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }),
    )
    await settle()
    expect(document.querySelector('[role="dialog"]')).toBeNull()
    expect(document.activeElement).toBe(expand.element)
  })
  it('closes the overlay from the explicit Close button', async () => {
    const wrapper = fixture({ visibleChildCount: 1 })
    await settle()
    await wrapper.get('button').trigger('click')
    await settle()
    document
      .querySelector<HTMLButtonElement>('[role="dialog"] button[data-component="IconButton"]')
      ?.click()
    await settle()
    expect(document.querySelector('[role="dialog"]')).toBeNull()
    expect(document.activeElement).toBe(wrapper.get('button').element)
  })
  it('observes each auto-truncated child, reserves toggle width, and disconnects on unmount', async () => {
    const observers: {
      callback: IntersectionObserverCallback
      observe: ReturnType<typeof vi.fn>
      disconnect: ReturnType<typeof vi.fn>
      options?: IntersectionObserverInit
    }[] = []
    vi.stubGlobal(
      'IntersectionObserver',
      class {
        constructor(callback: IntersectionObserverCallback, options?: IntersectionObserverInit) {
          observers.push({ callback, options, observe: this.observe, disconnect: this.disconnect })
        }
        observe = vi.fn()
        disconnect = vi.fn()
      },
    )
    const wrapper = fixture({ visibleChildCount: 'auto', overflowStyle: 'inline' })
    expect(observers[0]?.observe).toHaveBeenCalledTimes(5)
    const entries = wrapper.findAll('[data-index]').map(
      (item, index) =>
        ({
          target: item.element,
          isIntersecting: index < 2,
        }) as IntersectionObserverEntry,
    )
    observers[0]?.callback(entries, {} as IntersectionObserver)
    await settle()
    await vi.waitFor(() => expect(wrapper.get('button').text()).toContain('+3'))
    expect(observers.at(-1)?.options?.root).toBe(wrapper.element)
    expect(observers.at(-1)?.options?.threshold).toBe(1)
    await wrapper.get('button').trigger('click')
    await settle()
    expect(wrapper.attributes('data-overflow')).toBe('inline')
    expect(observers[0]?.disconnect).toHaveBeenCalled()
    await wrapper.get('button').trigger('click')
    await settle()
    expect(wrapper.find('button').exists()).toBe(false)
    observers.at(-1)?.callback(entries, {} as IntersectionObserver)
    await settle()
    expect(wrapper.get('button').text()).toContain('+3')
    const latest = observers.at(-1)
    wrapper.unmount()
    wrappers.splice(wrappers.indexOf(wrapper), 1)
    expect(latest?.disconnect).toHaveBeenCalled()
  })

  it('updates the overlay toggle count when auto-truncated visibility changes', async () => {
    const callbacks: IntersectionObserverCallback[] = []
    vi.stubGlobal(
      'IntersectionObserver',
      class {
        constructor(callback: IntersectionObserverCallback) {
          callbacks.push(callback)
        }
        observe = vi.fn()
        disconnect = vi.fn()
      },
    )
    const wrapper = fixture({ visibleChildCount: 'auto' })
    const notify = async (visibleCount: number) => {
      callbacks.at(-1)!(
        wrapper.findAll('[data-index]').map(
          (node, index) =>
            ({
              target: node.element,
              isIntersecting: index < visibleCount,
            }) as IntersectionObserverEntry,
        ),
        {} as IntersectionObserver,
      )
      await settle()
    }
    await notify(3)
    expect(wrapper.get('button').text()).toContain('+2')
    await notify(2)
    expect(wrapper.get('button').text()).toContain('+3')
    await notify(5)
    expect(wrapper.find('button').exists()).toBe(false)
  })
})
